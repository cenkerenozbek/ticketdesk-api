CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('USER', 'AGENT'))
);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL CHECK (length(trim(title)) > 0),
    description VARCHAR(5000) NOT NULL CHECK (length(trim(description)) > 0),
    priority VARCHAR(16) NOT NULL CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED')),
    created_at TIMESTAMPTZ NOT NULL,
    creator_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE ticket_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    changed_by BIGINT NOT NULL REFERENCES users(id),
    from_status VARCHAR(16) NOT NULL,
    to_status VARCHAR(16) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL,
    CHECK ((from_status = 'OPEN' AND to_status = 'IN_PROGRESS')
        OR (from_status = 'IN_PROGRESS' AND to_status = 'RESOLVED'))
);

-- Support owner-scoped lists and agent status filters, both ordered by creation.
CREATE INDEX idx_tickets_creator_created ON tickets (creator_id, created_at DESC, id);
CREATE INDEX idx_tickets_status_created ON tickets (status, created_at DESC, id);
CREATE INDEX idx_history_ticket_id ON ticket_status_history (ticket_id, id);
